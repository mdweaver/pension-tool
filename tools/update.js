#!/usr/bin/env node
// Run after changing js/schema.js:   node tools/update.js
// Regenerates schema.lock.json (the record of field keys and block shapes that saved data depends on)
// and data_dictionary.csv. Refuses if a change would orphan saved data (a field or block removed or
// renamed, a type changed, a block switched between one-off and repeatable) unless you pass
// --allow-breaking, which records the change in the lock file so the CI check accepts it.
// A breaking change also needs a data migration for records already saved: see CLAUDE.md.
const fs = require('fs'), path = require('path');
const { ROOT, loadSchema, schemaShape, compareShapes, dataDictionaryCSV, stable } = require('./lib');

const allow = process.argv.includes('--allow-breaking');
const lockFile = path.join(ROOT, 'schema.lock.json');
const S = loadSchema();
const shape = schemaShape(S);
const old = fs.existsSync(lockFile) ? JSON.parse(fs.readFileSync(lockFile, 'utf8')) : null;
let acknowledged = (old && old.acknowledged_breaking) || [];

if (old) {
  const { breaking, warnings, added } = compareShapes(old.shape, shape);
  for (const w of warnings) console.log('warning: ' + w);
  if (added.length) console.log('added: ' + added.join(', '));
  if (breaking.length) {
    console.log('\nBreaking changes (saved records already use these):\n  - ' + breaking.join('\n  - '));
    if (!allow) {
      console.log('\nNot updated. Keep the old keys (change only labels/help), or if this is intended,\n' +
        're-run with --allow-breaking and add a data migration for existing records (see CLAUDE.md).');
      process.exit(1);
    }
    acknowledged = acknowledged.concat(breaking.map(b => ({ change: b, date: new Date().toISOString().slice(0, 10) })));
    console.log('\nRecorded as acknowledged breaking changes.');
  }
}
fs.writeFileSync(lockFile, stable({ _note: 'Generated by tools/update.js. Do not edit by hand.', acknowledged_breaking: acknowledged, shape }));
fs.writeFileSync(path.join(ROOT, 'data_dictionary.csv'), dataDictionaryCSV(S));
console.log('Updated schema.lock.json and data_dictionary.csv');
